// Inyectar fuente brutalista (Space Mono y Syne) desde Google Fonts
(function() {
  const fontLink = document.createElement('link');
  fontLink.rel = 'stylesheet';
  fontLink.href = 'https://fonts.googleapis.com/css2?family=JetBrains+Mono:ital,wght@0,400;0,700;0,800;1,400&family=Syne:wght@700;800&display=swap';
  document.head.appendChild(fontLink);
})();
